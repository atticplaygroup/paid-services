CREATE DATABASE IF NOT EXISTS realworld CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE realworld;
CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(255) PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE,
 bio TEXT NULL, image TEXT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE TABLE IF NOT EXISTS articles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(255) NOT NULL UNIQUE,
 title VARCHAR(255) NOT NULL, description TEXT NOT NULL, body MEDIUMTEXT NOT NULL,
 author_id VARCHAR(255) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY (author_id) REFERENCES users(id), INDEX(created_at)
);
CREATE TABLE IF NOT EXISTS article_tags (
 article_id BIGINT UNSIGNED NOT NULL, tag VARCHAR(100) NOT NULL, position INT NOT NULL,
 PRIMARY KEY(article_id,tag), FOREIGN KEY(article_id) REFERENCES articles(id) ON DELETE CASCADE, INDEX(tag)
);
CREATE TABLE IF NOT EXISTS follows (
 follower_id VARCHAR(255) NOT NULL, followed_id VARCHAR(255) NOT NULL,
 PRIMARY KEY(follower_id,followed_id), FOREIGN KEY(follower_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(followed_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id VARCHAR(255) NOT NULL, article_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(user_id,article_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(article_id) REFERENCES articles(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, article_id BIGINT UNSIGNED NOT NULL,
 author_id VARCHAR(255) NOT NULL, body TEXT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY(article_id) REFERENCES articles(id) ON DELETE CASCADE, FOREIGN KEY(author_id) REFERENCES users(id)
);
